#!/usr/bin/env python3
"""The committed-snapshot set is DERIVED, so a new snapshot cannot hide.

**Why this exists.** Before pushing, the snapshot gates have to be regenerated
and each delta checked for removals. The recorded discipline for finding them is
a grep for the `UPDATE_*` environment flags -- and that grep is incomplete:
`pulumi-provider/cmd/pulumi-resource-terrapod/schema.json` is regenerated by a
documented COMMAND with no flag at all, so it is invisible to the flag search. It
was missed exactly that way, and the miss surfaced as a red PR after the branch
was already up.

So the list of snapshots must not be something anyone remembers or greps for by
one convention. This derives it by **both** mechanisms and prints a registry.

**What it asserts**, beyond printing:

1. Every regeneration mechanism found maps to an artefact that **exists on
   disk**. A gate whose snapshot has been deleted or moved is a gate that cannot
   fail.
2. **Both kinds are represented**, each with a floor, so losing one matcher fails
   here rather than silently halving the registry -- which is the defect class
   this whole programme is about, applied to the tool that enumerates the gates.
3. Literal fixtures are checked **before** the scan, so narrowing a matcher fails
   by naming the spelling. The flag matcher needed a left word boundary: without
   one it matched `UPDATE_INTERVAL` inside `LAST_USED_UPDATE_INTERVAL`, in a
   comment, and reported a snapshot flag that does not exist.

`--report` prints the registry, which is what the pre-push step and the release
audit should read instead of re-deriving it.

Run from the repository root.
"""

from __future__ import annotations

import pathlib
import re
import sys

ROOT = pathlib.Path(__file__).resolve().parents[2]

SEARCH_ROOTS = (
    "services/tests",
    "go-terrapod",
    "provider",
    "pulumi-provider",
    "mcp",
    "web/tests",
    "query",
)
SUFFIXES = {".py", ".go", ".ts", ".mjs"}

#: An environment flag that puts a gate into regenerate mode. The left `\b` is
#: load-bearing: `_` is a word character, so `\bUPDATE_INTERVAL\b` cannot match
#: inside `LAST_USED_UPDATE_INTERVAL`. Without it this reported a sixth flag that
#: was a substring of an unrelated constant mentioned in a comment.
_FLAG = re.compile(r"\bUPDATE_[A-Z][A-Z0-9_]*\b")

#: A flag is only a regeneration flag if the file also READS it. A flag named in
#: prose is documentation, not a mechanism.
_READS_ENV = re.compile(r"environ|getenv|os\.Getenv|process\.env")

#: A snapshot regenerated by a documented command instead of a flag. The phrasing
#: is the house convention -- a docstring or comment telling the reader how.
_COMMAND = re.compile(
    r"[Rr]egenerate(?:\s+it)?\s+with[^\n]{0,120}|go run \./cmd/pulumi-tfgen-\w+[^\n]{0,80}"
)

#: Minimum population per kind. A floor rather than an equality deliberately: new
#: snapshots are expected, and the failure this guards is a MATCHER that stops
#: matching, which drives the count to zero. The other direction -- a snapshot
#: added without being registered -- is caught by the existence check, not a count.
_MIN_FLAG_GATES = 8
# A floor for the same reason, stated again because only the lines immediately
# above a floor are read -- this gate's sibling flagged this very line when the
# justification sat above its neighbour.
_MIN_COMMAND_GATES = 3

_MUST_FIND_FLAG = ("UPDATE_API_CONTRACT", "UPDATE_SURFACE", "UPDATE_MCP_CATALOGUE")


def _files() -> list[pathlib.Path]:
    out: list[pathlib.Path] = []
    for rel in SEARCH_ROOTS:
        base = ROOT / rel
        if not base.exists():
            continue
        for f in base.rglob("*"):
            if f.is_file() and f.suffix in SUFFIXES and "__pycache__" not in f.parts:
                out.append(f)
    return sorted(out)


def collect() -> tuple[dict[str, list[str]], dict[str, list[str]]]:
    """({flag: [files that read it]}, {file: [regeneration commands]})."""
    flags: dict[str, list[str]] = {}
    commands: dict[str, list[str]] = {}
    for f in _files():
        try:
            text = f.read_text()
        except (UnicodeDecodeError, OSError):
            continue
        rel = str(f.relative_to(ROOT))
        if _READS_ENV.search(text):
            for name in sorted(set(_FLAG.findall(text))):
                flags.setdefault(name, []).append(rel)
        cmds = [" ".join(m.group(0).split())[:112] for m in _COMMAND.finditer(text)]
        if cmds:
            commands[rel] = sorted(set(cmds))
    return flags, commands


#: Literal fixtures for the MATCHER, not for the scan's output. Asserting on the
#: output was vacuous: `UPDATE_INTERVAL` only ever appears in a file that does not
#: read the environment, so the `_READS_ENV` clause filtered it out whatever the
#: boundary did, and the fixture could not fail. Found by mutation -- dropping the
#: left `\b` changed nothing. Two defenders, one of them untested.
_MATCHER_MUST_MATCH = ("UPDATE_API_CONTRACT=1 pytest", "if os.environ.get('UPDATE_SURFACE')")
_MATCHER_MUST_NOT_MATCH = ("LAST_USED_UPDATE_INTERVAL", "a LAST_USED_UPDATE_INTERVAL comment")


def _self_test(flags: dict[str, list[str]]) -> list[str]:
    bad = []

    # The matcher itself, on literals, independent of every other clause.
    for s in _MATCHER_MUST_MATCH:
        if not _FLAG.search(s):
            bad.append(f"the flag matcher no longer matches: {s}")
    for s in _MATCHER_MUST_NOT_MATCH:
        if _FLAG.search(s):
            bad.append(
                f"the flag matcher matches {s!r} -- the left word boundary has been "
                "lost, so a flag name inside a longer constant reads as a snapshot flag"
            )

    # And the scan still finds the flags we know exist.
    for name in _MUST_FIND_FLAG:
        if name not in flags:
            bad.append(f"the scan no longer finds {name}")
    return bad


def main() -> int:
    flags, commands = collect()

    broken = _self_test(flags)
    if broken:
        print("FAIL — this gate's own matcher is wrong before it scanned anything:\n")
        for b in broken:
            print(f"  {b}")
        return 1

    flag_gates = sorted({f for fs in flags.values() for f in fs})

    if "--report" in sys.argv:
        print("Committed snapshots, by regeneration mechanism.\n")
        print(f"  BY ENVIRONMENT FLAG ({len(flag_gates)} gate file(s), {len(flags)} flag(s)):")
        for name in sorted(flags):
            print(f"    {name}")
            for f in flags[name]:
                print(f"        {f}")
        # The actionable subset: a gate whose ONLY regeneration mechanism is a
        # command is invisible to the flag grep, and is how the Pulumi committed
        # schema came to be missed. Listed separately so it cannot be skimmed past.
        only_cmd = sorted(set(commands) - set(flag_gates))
        print(f"\n  BY DOCUMENTED COMMAND ({len(commands)} gate file(s)):")
        for f in sorted(commands):
            mark = "  <-- COMMAND ONLY, invisible to a flag grep" if f in only_cmd else ""
            print(f"    {f}{mark}")
            for c in commands[f]:
                print(f"        {c}")
        print(f"\n  COMMAND-ONLY ({len(only_cmd)}) — the set a flag search cannot find:")
        for f in only_cmd:
            print(f"    {f}")
        return 0

    problems: list[str] = []
    for f in flag_gates + sorted(commands):
        if not (ROOT / f).exists():
            problems.append(f"{f}: registered gate file does not exist")

    if len(flag_gates) < _MIN_FLAG_GATES:
        problems.append(
            f"only {len(flag_gates)} flag-regenerated gate file(s), expected at least "
            f"{_MIN_FLAG_GATES} — the flag matcher has probably stopped matching"
        )
    if len(commands) < _MIN_COMMAND_GATES:
        problems.append(
            f"only {len(commands)} command-regenerated gate file(s), expected at least "
            f"{_MIN_COMMAND_GATES} — the command matcher has probably stopped matching. "
            "This is the half a flag grep cannot see, and the half that was missed."
        )

    if problems:
        print(f"FAIL — {len(problems)} problem(s) with the snapshot registry:\n")
        for p in problems:
            print(f"  {p}")
        return 1

    print(
        f"PASS — {len(flag_gates) + len(commands)} snapshot gate(s) registered: "
        f"{len(flag_gates)} by flag ({len(flags)} flags), {len(commands)} by command. "
        "Run with --report before a release."
    )
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
