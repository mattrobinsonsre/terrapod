// Command pulumi-resource-terrapod is the Pulumi provider plugin binary.
//
// Pulumi resolves a provider plugin by name and version and runs it as a
// subprocess, so this is the artifact an agent run has to be able to obtain.
// Inside a Terrapod run it always can: `plugin_override_env` points every
// plugin download at the loopback cache proxy with a `.*` pattern, so whatever
// URL the plugin declares for itself is overridden and the proxy serves it with
// the run's own credential attached (#1483, #1906).
package main

import (
	"context"
	_ "embed"
	"fmt"
	"os"

	pftfbridge "github.com/pulumi/pulumi-terraform-bridge/v3/pkg/pf/tfbridge"

	terrapod "github.com/mattrobinsonsre/terrapod/pulumi-provider"
)

// The Pulumi Package Schema, generated by `pulumi-tfgen-terrapod` and committed
// beside this file. The plugin serves it to the Pulumi engine, so it has to be
// the schema the SDKs were generated from -- embedding rather than reading it at
// runtime is what makes that the same bytes by construction.
//
//go:embed schema.json
var schema []byte

// Set via ldflags at build time. Semver, because the bridge validates it and
// refuses to serve a version it cannot parse.
var version = terrapod.SourceBuildVersion

func main() {
	// The embedded schema carries no version -- tfgen clears it deliberately, and
	// the plugin-framework server serves these bytes verbatim, so this is the only
	// place it can come from. Without it `pulumi package add` cannot generate an
	// SDK in any language (#2267). See `SchemaWithVersion` for the whole account.
	versioned, err := terrapod.SchemaWithVersion(schema, version)
	if err != nil {
		// Fatal rather than serving the schema unversioned. A plugin that starts
		// and then cannot generate an SDK is the failure this replaced: it looks
		// healthy, answers `--version`, and fails at the practitioner's first
		// command with an error about a schema they did not write.
		fmt.Fprintf(os.Stderr, "pulumi-resource-terrapod: %v\n", err)
		os.Exit(1)
	}

	pftfbridge.Main(
		context.Background(),
		terrapod.Namespace,
		terrapod.Provider(version),
		pftfbridge.ProviderMetadata{PackageSchema: versioned},
	)
}
